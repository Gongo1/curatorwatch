/**
 * Run tests to verify extraction logic
 */
export function runExtractionTests(): { passed: number; failed: number; results: string[] } {
  const results: string[] = [];
  let passed = 0;
  let failed = 0;

  for (const [input, expected] of Object.entries(EXTRACTION_TEST_CASES)) {
    const actual = extractCuratorFromVaultName(input);
    const match = actual.toLowerCase() === expected.toLowerCase();

    if (match) {
      passed++;
      results.push(`✓ "${input}" → "${actual}"`);
    } else {
      failed++;
      results.push(`✗ "${input}" → "${actual}" (expected: "${expected}")`);
    }
  }

  return { passed, failed, results };
}
