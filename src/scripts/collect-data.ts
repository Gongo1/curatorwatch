const BATCH_SIZE = 100; // Vaults per API request
// Vaults written per chunk: each write step is one statement per chunk, not
// one per vault (per-vault round trips cost ~4s/vault on the pooler).
const CHUNK_SIZE = 50;
const ROWS_PER_STATEMENT = 500; // Cap on rows in one INSERT / UPDATE ... VALUES
const API_CONCURRENCY = 4; // Per-vault transaction/reallocation fetches in flight
const TRANSACTIONS_PER_VAULT = 50;
const MIN_TVL_USD = 1000; // Skip vaults below $1000 TVL
const API_DELAY_MS = 100; // Delay between API calls to respect rate limits

