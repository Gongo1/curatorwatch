export type MorphoGeneration = "v1" | "v2";

// A chain/generation that returns zero vaults while the DB still tracks more
// than this many active vaults for it is treated as a broken source, not an
// empty market.
const EMPTY_SOURCE_DB_THRESHOLD = 10;

export interface CollectionOptions {
  fetchAll?: boolean; // Fetch all vaults (default: true)
  skipTransactions?: boolean; // Skip transaction fetching for speed
  skipReallocations?: boolean; // Skip reallocation fetching for speed
  skipMarketAllocations?: boolean; // Skip market allocation collection
  skipLiquidations?: boolean; // Skip liquidation collection
  minTvlUsd?: number; // Minimum TVL to include
  verbose?: boolean; // Verbose logging
  // Restrict the run to these chains (cron lanes: Ethereum alone is ~2/3 of
  // the vault count and must finish within the function budget, so the other
  // chains run in their own invocation). Default: all MORPHO_CHAINS.
  chainIds?: number[];
  // Restrict the run to these vault generations (cron lanes: Ethereum V1 and
  // V2 each run in their own invocation). Default: both.
  generations?: MorphoGeneration[];
  // Stop starting new vault chunks this long after the run began (the cron
  // keeps the rest of its function budget for the post-collection steps).
  // Deferred vaults are reported as a source error; they go first next run.
  // Default: no limit.
  timeBudgetMs?: number;
}

function log(message: string) {
  const timestamp = new Date().toISOString();
  console.log(`[${timestamp}] ${message}`);
}

function logError(message: string, error?: unknown) {
  const timestamp = new Date().toISOString();
  console.error(`[${timestamp}] ERROR: ${message}`, error ?? "");
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Fetch the canonical curator registry (org id/name + addresses across every
 * chain) once per run and index it by lowercase curator address. Used to
 * resolve a vault's curator address to the same Curator row regardless of
 * which chain the vault lives on. An empty map (registry fetch failure)
 * degrades gracefully to address-only resolution — today's behavior.
 */
export async function fetchMorphoCuratorRegistry(): Promise<Map<string, MorphoCanonicalCurator>> {
  const byAddress = new Map<string, MorphoCanonicalCurator>();
  let skip = 0;

  while (true) {
    try {
      const response = await morphoClient.request<{
        curators: { items: MorphoCanonicalCurator[] };
      }>(GET_MORPHO_CURATORS, { first: BATCH_SIZE, skip });

      const items = response.curators.items;
      for (const org of items) {
        for (const a of org.addresses) {
          const key = a.address.toLowerCase();
          if (!byAddress.has(key)) byAddress.set(key, org);
        }
      }
      if (items.length < BATCH_SIZE) break;
      skip += BATCH_SIZE;
      await sleep(API_DELAY_MS);
    } catch (error) {
      logError(`Failed to fetch curator registry at skip=${skip}`, error);
      break;
    }
  }

  log(`Curator registry: ${byAddress.size} curator addresses mapped`);
  return byAddress;
}

/**
 * Effective TVL floor for a chain: the per-chain floor, or the caller's
 * override when it is stricter. (The cron passes minTvlUsd=1000, which must
 * not lower the $50k floor on newly added chains.)
 */
function effectiveMinTvl(chain: MorphoChainConfig, options: CollectionOptions): number {
  return Math.max(chain.minTvlUsd, options.minTvlUsd ?? MIN_TVL_USD);
}

/**
 * Fetch all V2 vaults on one chain from the Morpho API with pagination.
 * Returns vaults sorted by TVL descending. A failure after the first page
 * returns the pages already fetched and records the failure in `pageErrors`
 * (the caller must surface it — a truncated list is not a clean run).
 */
export async function fetchAllVaults(
  chain: MorphoChainConfig,
  options: CollectionOptions = {},
  pageErrors: string[] = []
): Promise<MorphoVaultV2[]> {
  const allVaults: MorphoVaultV2[] = [];
  let skip = 0;
  let hasMore = true;
  const minTvl = effectiveMinTvl(chain, options);

  log(`Fetching V2 vaults for chain ${chain.chainId} (min TVL: $${minTvl.toLocaleString()})...`);

  while (hasMore) {
    try {
      const response = await morphoClient.request<VaultV2sResponse>(
        GET_VAULTS_V2_PAGINATED,
        {
          first: BATCH_SIZE,
          skip,
          chainId: chain.chainId,
          minTvl,
        }
      );

      const vaults = response.vaultV2s.items;

      if (vaults.length === 0) {
        hasMore = false;
      } else {
        // Filter by minimum TVL (backstop — the where-clause already applies it)
        // VaultV2.avgApy is no longer served: fall back to the (sanitized) spot
        // apy, which tracked avgApy within 0.04pp (median) over Aug 20-26 2026.
        // Keeps the vault-page APY, curator gross APY and APY alerts alive.
        const validVaults = vaults
          .filter((v) => (v.totalAssetsUsd ?? 0) >= minTvl)
          .map((v) => ({ ...v, avgApy: v.avgApy ?? sanitizeApyForStorage(v.apy) }));
        allVaults.push(...validVaults);

        if (options.verbose) {
          log(`  Fetched batch ${skip}-${skip + vaults.length}: ${validVaults.length}/${vaults.length} valid vaults`);
        }

        // If we got fewer vaults than batch size, or last vault is below min TVL, we're done
        if (vaults.length < BATCH_SIZE) {
          hasMore = false;
        } else {
          // Check if last vault is below minimum TVL (since sorted by TVL)
          const lastVault = vaults[vaults.length - 1];
          if ((lastVault.totalAssetsUsd ?? 0) < minTvl) {
            hasMore = false;
          } else {
            skip += BATCH_SIZE;
            // Small delay to respect rate limits
            await sleep(API_DELAY_MS);
          }
        }
      }
    } catch (error) {
      logError(`Failed to fetch vaults batch at skip=${skip} (chain ${chain.chainId})`, error);
      // First page failing means the query itself is broken (schema drift) or
      // the API is down — rethrow so the run fails loudly instead of quietly
      // collecting zero vaults (V2 was silently frozen Aug 26 -> Sep 30 this way).
      if (skip === 0) throw error;
      pageErrors.push(
        `V2 page at skip=${skip} failed (list truncated at ${allVaults.length}): ${error instanceof Error ? error.message : error}`
      );
      hasMore = false;
    }
  }

  log(`  Chain ${chain.chainId}: ${allVaults.length} V2 vaults`);
  return allVaults;
}

/**
 * Fetch all V1 (MetaMorpho) vaults on one chain, normalized to the common
 * shape. V1 vaults are separate contracts from V2 — both generations coexist.
 */
export async function fetchAllVaultsV1(
  chain: MorphoChainConfig,
  options: CollectionOptions = {},
  pageErrors: string[] = []
): Promise<MorphoVaultV2[]> {
  const allVaults: MorphoVaultV2[] = [];
  let skip = 0;
  let hasMore = true;
  const minTvl = effectiveMinTvl(chain, options);

  log(`Fetching V1 (MetaMorpho) vaults for chain ${chain.chainId} (min TVL: $${minTvl.toLocaleString()})...`);

  while (hasMore) {
    try {
      const response = await morphoClient.request<VaultsV1Response>(
        GET_VAULTS_V1_PAGINATED,
        {
          first: BATCH_SIZE,
          skip,
          chainId: chain.chainId,
          minTvl,
        }
      );

      const vaults = response.vaults.items;

      if (vaults.length === 0) {
        hasMore = false;
      } else {
        for (const v1 of vaults) {
          const common = v1ToCommonShape(v1);
          if (common && (common.totalAssetsUsd ?? 0) >= minTvl) {
            allVaults.push(common);
          }
        }

        if (vaults.length < BATCH_SIZE) {
          hasMore = false;
        } else {
          skip += BATCH_SIZE;
          await sleep(API_DELAY_MS);
        }
      }
    } catch (error) {
      logError(`Failed to fetch V1 vaults batch at skip=${skip} (chain ${chain.chainId})`, error);
      // First-page failure: fail loudly (see fetchAllVaults).
      if (skip === 0) throw error;
      pageErrors.push(
        `V1 page at skip=${skip} failed (list truncated at ${allVaults.length}): ${error instanceof Error ? error.message : error}`
      );
      hasMore = false;
    }
  }

  log(`  Chain ${chain.chainId}: ${allVaults.length} V1 vaults`);
  return allVaults;
}

/**
 * Validate vault data before processing.
 * Returns true if vault should be processed.
 */
function isValidVault(vault: MorphoVaultV2, minTvlUsd: number): { valid: boolean; reason?: string } {
  // Check minimum TVL
  if ((vault.totalAssetsUsd ?? 0) < minTvlUsd) {
    return { valid: false, reason: `TVL below $${minTvlUsd}` };
  }

  // Check for required fields
  if (!vault.address) {
    return { valid: false, reason: "Missing address" };
  }

  if (!vault.asset?.address) {
    return { valid: false, reason: "Missing asset info" };
  }

  return { valid: true };
}

